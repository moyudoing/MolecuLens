// Bohr → Å（与 cube 解析器约定一致）
constexpr double kAngstromPerBohr = 0.529177210903;

// 临时 cube 目录（RAII：析构时递归删除）
class TempCubeDir {
public:
    TempCubeDir() {
        static std::atomic<uint64_t> counter{0};
        const auto tick = std::chrono::steady_clock::now().time_since_epoch().count();
        path_ = fs::temp_directory_path() /
                ("moleculens_esp_test_" + std::to_string(static_cast<long long>(tick)) + "_" +
                 std::to_string(counter.fetch_add(1)));
        std::error_code ec;
        fs::create_directories(path_, ec);
    }
    ~TempCubeDir() {
        std::error_code ec;
        fs::remove_all(path_, ec);
    }
    TempCubeDir(const TempCubeDir&) = delete;
    TempCubeDir& operator=(const TempCubeDir&) = delete;

    const fs::path& path() const { return path_; }

private:
    fs::path path_;
};

struct CubeAtomSpec {
    int    atomicNumber = 0;   // Z
    double charge = 0.0;       // cube 第 2 列
    double xBohr = 0.0;        // 原子坐标（Bohr）
    double yBohr = 0.0;
    double zBohr = 0.0;
};

// 写 Gaussian cube 文件：2 行标题 / natoms+origin(Bohr) / 3 行网格向量(Bohr) /
// 原子行(Z charge x y z, Bohr) / 数据（x 外层、y 次之、z 最快）。
void writeCubeFile(const fs::path& path, int n, const std::array<double, 3>& originAngstrom,
                   double spacingAngstrom, const std::vector<CubeAtomSpec>& atoms,
                   const std::vector<float>& values, const std::string& title) {
    const std::size_t expectedValues = static_cast<std::size_t>(n) * static_cast<std::size_t>(n) *
                                       static_cast<std::size_t>(n);
    REQUIRE(values.size() == expectedValues);

    std::ofstream stream(path, std::ios::binary | std::ios::trunc);
    REQUIRE(stream.is_open());
    stream.setf(std::ios::scientific);
    stream.precision(10);

    const double bohrPerAngstrom = 1.0 / kAngstromPerBohr;
    stream << title << "\n";
    stream << "generated by MolecuLens esp_surface_tests\n";
    stream << atoms.size() << " " << originAngstrom[0] * bohrPerAngstrom << " "
           << originAngstrom[1] * bohrPerAngstrom << " " << originAngstrom[2] * bohrPerAngstrom
           << "\n";
    const double axisBohr = spacingAngstrom * bohrPerAngstrom;
    stream << n << " " << axisBohr << " 0 0\n";
    stream << n << " 0 " << axisBohr << " 0\n";
    stream << n << " 0 0 " << axisBohr << "\n";
    for (const CubeAtomSpec& atom : atoms) {
        stream << atom.atomicNumber << " " << atom.charge << " " << atom.xBohr << " "
               << atom.yBohr << " " << atom.zBohr << "\n";
    }
    std::size_t written = 0;
    for (float value : values) {
        stream << value;
        ++written;
        if (written % 6 == 0) {
            stream << "\n";
        } else {
            stream << " ";
        }
    }
    if (written % 6 != 0) {
        stream << "\n";
    }
}

// 合成测试数据：16³ 网格、间距 0.4 Å，球心偏离原点的各向同性高斯密度 ρ=iso 处
// 半径约 1.24 Å；ESP 为过球心的线性势（Hartree），表面同时存在明显正/负极值。
struct SyntheticCubes {
    std::string           densityPath;
    std::string           potentialPath;
    std::array<double, 3> centerAngstrom = {0.0, 0.0, 0.0};
};

constexpr int    kTestGridN = 16;
constexpr double kTestSpacing = 0.4;                        // Å
constexpr double kTestSigma = 0.8;                          // Å
constexpr float  kTestIsolevel = 0.3f;                      // a.u.

// CubeVolume 索引布局 = (ix*ny+iy)*nz+iz（x 外层、z 最快）
std::size_t voxelIndex(int ix, int iy, int iz) {
    const std::size_t ny = static_cast<std::size_t>(kTestGridN);
    const std::size_t nz = static_cast<std::size_t>(kTestGridN);
    return (static_cast<std::size_t>(ix) * ny + static_cast<std::size_t>(iy)) * nz +
           static_cast<std::size_t>(iz);
}

std::size_t testVoxelCount() {
    const std::size_t n = static_cast<std::size_t>(kTestGridN);
    return n * n * n;
}

SyntheticCubes writeSyntheticCubes(const fs::path& directory) {
    const std::array<double, 3> center = {1.0, -0.6, 0.8};
    const double halfExtent = 0.5 * (kTestGridN - 1) * kTestSpacing;   // 3.0 Å
    const std::array<double, 3> origin = {-halfExtent, -halfExtent, -halfExtent};

    std::vector<float> density(testVoxelCount());
    std::vector<float> potential(density.size());
    for (int ix = 0; ix < kTestGridN; ++ix) {
        const double x = origin[0] + ix * kTestSpacing;
        for (int iy = 0; iy < kTestGridN; ++iy) {
            const double y = origin[1] + iy * kTestSpacing;
            for (int iz = 0; iz < kTestGridN; ++iz) {
                const double z = origin[2] + iz * kTestSpacing;
                const std::size_t index = voxelIndex(ix, iy, iz);
                const double dx = x - center[0];
                const double dy = y - center[1];
                const double dz = z - center[2];
                const double r2 = dx * dx + dy * dy + dz * dz;
                density[index] = static_cast<float>(std::exp(-r2 / (2.0 * kTestSigma * kTestSigma)));
                // 过球心、沿 x 的线性势：球面上 V = ±0.03×r ≈ ±0.037 Hartree ≈ ±23 kcal/mol
                potential[index] = static_cast<float>(0.03 * dx);
            }
        }
    }

    const double bohrPerAngstrom = 1.0 / kAngstromPerBohr;
    std::vector<CubeAtomSpec> atoms;
    CubeAtomSpec atom;
    atom.atomicNumber = 8;
    atom.charge = 8.0;
    atom.xBohr = center[0] * bohrPerAngstrom;
    atom.yBohr = center[1] * bohrPerAngstrom;
    atom.zBohr = center[2] * bohrPerAngstrom;
    atoms.push_back(atom);

    const fs::path densityPath = directory / "density.cube";
    const fs::path potentialPath = directory / "esp.cube";
    writeCubeFile(densityPath, kTestGridN, origin, kTestSpacing, atoms, density,
                  "MolecuLens ESP test density");
    writeCubeFile(potentialPath, kTestGridN, origin, kTestSpacing, atoms, potential,
                  "MolecuLens ESP test potential");

    SyntheticCubes cubes;
    cubes.densityPath = densityPath.string();
    cubes.potentialPath = potentialPath.string();
    cubes.centerAngstrom = center;
    return cubes;
}

engine::EspSurfaceParams makeParams(const SyntheticCubes& cubes) {
    engine::EspSurfaceParams params;
    params.densityCubePath = cubes.densityPath;
    params.potentialCubePath = cubes.potentialPath;
    params.isolevel = kTestIsolevel;
    return params;
}

std::size_t countTriMeshVertices(engine::SceneCommandList& commands) {
    std::size_t total = 0;
    engine::CommandIterator iterator(commands);
    for (bool has = commands.first(iterator); has; has = commands.next(iterator)) {
        if (iterator.code() == engine::Cmd::TriMesh && iterator.payloadSize() >= 8) {
            const auto* header = reinterpret_cast<const engine::TriMeshHeader*>(iterator.payload());
            total += header->vertexCount;
        }
    }
    return total;
}

