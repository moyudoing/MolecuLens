#!/usr/bin/env python3
"""MolecuLens · cmake/spv_to_header.py —— SPIR-V 二进制 → C++ 头文件

用法: spv_to_header.py input.spv output.h
生成的头文件含:
  - 对齐到 4 字节的字节数组（moleculens_spv_<name>）
  - 长度常量（moleculens_spv_<name>_len）

规格来源：M0 工程脚手架 §3.3。
"""
import sys
import os


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: spv_to_header.py <input.spv> <output.h>", file=sys.stderr)
        return 1

    in_path, out_path = sys.argv[1], sys.argv[2]
    with open(in_path, "rb") as f:
        data = f.read()

    base = os.path.splitext(os.path.basename(out_path))[0]
    # 头文件名（如 triangle_vert.h）→ 符号名（triangle_vert）
    name = base.replace("-", "_").replace(".", "_")

    # 注意：不带命名空间——由使用方在匿名命名空间内 include（engine 两处），
    #       符号直接落入包含处作用域。
    lines = [
        "// Auto-generated by spv_to_header.py -- do not edit.",
        f"// Source SPIR-V: {os.path.basename(in_path)} ({len(data)} bytes)",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstddef>",
        "",
        f"inline constexpr size_t {name}_len = {len(data)};",
        "",
        "alignas(4) static const uint8_t " + name + "[] = {",
    ]

    # 每行 16 字节
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

    lines += [
        "};",
        "",
    ]

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"wrote {out_path} ({len(data)} bytes -> {name})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
